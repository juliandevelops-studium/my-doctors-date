// Command seed prints idempotent SQL that fills an empty database with demo content: specialties, services,
// staff, doctors with working hours, patients and bookings. Pipe it into psql (see scripts/seed.sh).
//
// Demo data only. All accounts share one password (DEMO_PASSWORD) and have no MFA secret, so every user has to
// enrol MFA at the first login.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"math/rand"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/juliandevelops-studium/my-doctors-date/services/user_service/internal/password"
)

const defaultPassword = "Demo-Passwort-2026!"

type person struct {
	id, first, last, email, phone string
	role                          string
	specialty                     string // doctors only
	weekdays                      []int  // doctors only, ISO 1 = Monday
	street, postal, city          string // patients only
	mainDoctor                    int    // patients only, index into doctors
}

type service struct {
	Name     string  `json:"name"`
	Duration int     `json:"duration_minutes"`
	Spec     *string `json:"specialty"`
	IsOther  bool    `json:"is_other"`
}

func main() {
	seedDir := flag.String("seeds", "services/database_middleware/seeds", "directory with specialties.json and services.json")
	flag.Parse()

	pw := os.Getenv("DEMO_PASSWORD")
	if pw == "" {
		pw = defaultPassword
	}

	specialties, services := loadSeeds(*seedDir)
	staff, doctors, patients := people()

	for _, p := range append(append(append([]person{}, staff...), doctors...), patients...) {
		if v := password.Validate(pw, p.email); len(v) > 0 {
			fatal("DEMO_PASSWORD rejected by the password policy: %v", v)
		}
	}
	hash, err := password.Hash(pw)
	if err != nil {
		fatal("hash: %v", err)
	}

	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("-- Demo data generated by services/user_service/cmd/seed. Safe to run more than once.")
	w("BEGIN;")

	for i, s := range specialties {
		w("INSERT INTO specialties (id, name) VALUES (%s, %s) ON CONFLICT DO NOTHING;", q(uuid(1, i)), q(s))
	}
	for _, s := range services {
		if s.IsOther {
			continue // created by migration 0010
		}
		w("INSERT INTO services (id, name, duration_minutes, specialty_id, is_other) VALUES (%s, %s, %d, (SELECT id FROM specialties WHERE name = %s), false) ON CONFLICT DO NOTHING;",
			q(uuid(2, indexOf(services, s))), q(s.Name), s.Duration, qp(s.Spec))
	}

	all := append(append(append([]person{}, staff...), doctors...), patients...)
	for _, p := range all {
		w("INSERT INTO users (id, first_name, last_name, email, phone, password_hash, status, email_verified_at) VALUES (%s, %s, %s, %s, %s, %s, 'active', now()) ON CONFLICT DO NOTHING;",
			q(p.id), q(p.first), q(p.last), q(p.email), q(p.phone), q(hash))
		w("INSERT INTO user_roles (user_id, role) VALUES (%s, %s) ON CONFLICT DO NOTHING;", q(p.id), q(p.role))
	}
	for _, d := range doctors {
		w("INSERT INTO doctors (user_id) VALUES (%s) ON CONFLICT DO NOTHING;", q(d.id))
		w("INSERT INTO doctor_specialties (doctor_id, specialty_id) VALUES (%s, (SELECT id FROM specialties WHERE name = %s)) ON CONFLICT DO NOTHING;", q(d.id), q(d.specialty))
		for _, wd := range d.weekdays {
			for i, blk := range [][2]string{{"08:00", "12:00"}, {"13:00", "17:00"}} {
				id := uuid(3, indexOfPerson(doctors, d)*100+wd*10+i)
				w("INSERT INTO working_days (id, doctor_id, weekday, start_time, end_time) VALUES (%s, %s, %d, %s, %s) ON CONFLICT DO NOTHING;",
					q(id), q(d.id), wd, q(blk[0]), q(blk[1]))
			}
		}
	}
	for _, p := range patients {
		w("INSERT INTO patients (user_id, street, postal_code, city, main_doctor_id) VALUES (%s, %s, %s, %s, %s) ON CONFLICT DO NOTHING;",
			q(p.id), q(p.street), q(p.postal), q(p.city), q(doctors[p.mainDoctor].id))
	}

	for _, line := range bookings(doctors, patients, services) {
		w("%s", line)
	}

	w("COMMIT;")
	fmt.Print(b.String())
	fmt.Fprintf(os.Stderr, "demo users: %d staff, %d doctors, %d patients; password: %s\n", len(staff), len(doctors), len(patients), pw)
}

// bookings fills each doctor's working time of the last week and the next two weeks. Slots of one doctor are laid
// out one after another, so they never hit the overlap constraint (bookings_no_doctor_overlap).
func bookings(doctors, patients []person, services []service) []string {
	loc, err := time.LoadLocation("Europe/Berlin")
	if err != nil {
		fatal("timezone: %v", err)
	}
	rng := rand.New(rand.NewSource(42)) //nolint:gosec // deterministic demo data
	now := time.Now().In(loc)
	today := time.Date(now.Year(), now.Month(), now.Day(), 0, 0, 0, 0, loc)

	var out []string
	n := 0
	for di, d := range doctors {
		var offered []service
		for _, s := range services {
			if s.Spec != nil && *s.Spec == d.specialty {
				offered = append(offered, s)
			}
		}
		for off := -7; off <= 14; off++ {
			day := today.AddDate(0, 0, off)
			if !contains(d.weekdays, isoWeekday(day)) {
				continue
			}
			for _, blk := range [][2]int{{8, 12}, {13, 17}} {
				at := day.Add(time.Duration(blk[0]) * time.Hour)
				end := day.Add(time.Duration(blk[1]) * time.Hour)
				for {
					s := offered[rng.Intn(len(offered))]
					dur := time.Duration(s.Duration) * time.Minute
					if at.Add(dur).After(end) {
						break
					}
					if rng.Intn(3) != 0 { // leave about a third of the slots free
						n++
						p := patients[rng.Intn(len(patients))]
						out = append(out, fmt.Sprintf(
							"INSERT INTO bookings (id, patient_id, doctor_id, service_id, starts_at, ends_at, reason, status) VALUES (%s, %s, %s, (SELECT id FROM services WHERE name = %s), %s, %s, %s, %s) ON CONFLICT DO NOTHING;",
							q(uuid(4, di*10000+n)), q(p.id), q(d.id), q(s.Name),
							q(at.Format(time.RFC3339)), q(at.Add(dur).Format(time.RFC3339)),
							q(reasons[rng.Intn(len(reasons))]), q(status(rng, at.Before(now)))))
					}
					at = at.Add(dur)
				}
			}
		}
	}
	return out
}

var reasons = []string{"Routine check", "Back pain", "Skin irritation", "Vaccination before travel", "Follow-up after treatment", "Annual screening"}

func status(rng *rand.Rand, past bool) string {
	r := rng.Intn(10)
	switch {
	case r == 0:
		return "storniert"
	case past:
		return "abgeschlossen"
	case r < 3:
		return "angefragt"
	default:
		return "bestaetigt"
	}
}


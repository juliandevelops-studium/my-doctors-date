func loadSeeds(dir string) (specialties []string, services []service) {
	var sp struct {
		Specialties []struct {
			Name string `json:"name"`
		} `json:"specialties"`
	}
	var sv struct {
		Services []service `json:"services"`
	}
	read(filepath.Join(dir, "specialties.json"), &sp)
	read(filepath.Join(dir, "services.json"), &sv)
	for _, s := range sp.Specialties {
		specialties = append(specialties, s.Name)
	}
	return specialties, sv.Services
}

func read(path string, v any) {
	data, err := os.ReadFile(path)
	if err != nil {
		fatal("%v", err)
	}
	if err := json.Unmarshal(data, v); err != nil {
		fatal("%s: %v", path, err)
	}
}

func isoWeekday(t time.Time) int {
	if t.Weekday() == time.Sunday {
		return 7
	}
	return int(t.Weekday())
}

func contains(xs []int, x int) bool {
	for _, v := range xs {
		if v == x {
			return true
		}
	}
	return false
}

func indexOf(xs []service, s service) int {
	for i, v := range xs {
		if v.Name == s.Name {
			return i
		}
	}
	return -1
}

func indexOfPerson(xs []person, p person) int {
	for i, v := range xs {
		if v.id == p.id {
			return i
		}
	}
	return -1
}

// uuid builds a stable id, so that a second run hits ON CONFLICT instead of creating duplicates.
func uuid(kind, n int) string { return fmt.Sprintf("d0000000-%04d-4000-8000-%012d", kind, n) }

func q(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

func qp(s *string) string {
	if s == nil {
		return "NULL"
	}
	return q(*s)
}

func fatal(format string, a ...any) {
	fmt.Fprintf(os.Stderr, "seed: "+format+"\n", a...)
	os.Exit(1)
}
